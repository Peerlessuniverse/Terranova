"""Build the lightweight browser runtime of the TERRA NOVA opening from the cinematic-motlab project.

- Images  -> runtime/img/*.webp (native size, lossy WebP; alpha kept for the Gaia cut-outs)
- Scenes  -> runtime/js/scenes.js (all 23 scene modules bundled; subtitles removed from the canvas,
             they are rendered as accessible HTML captions instead)
- Engine  -> runtime/js/engine.js (cinematic.js + one-time baked image filters, no per-frame ctx.filter)
- Captions-> runtime/captions.json, subtitle-id.vtt, subtitle-en.vtt, transcript-id.md (from _build/timings.json)
- Manifest-> runtime/manifest.json
The source project (../cinematic-motlab) is read only.

Usage (from cinematic-web/): python tools/build_web.py
"""
import glob
import json
import os
import re

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.normpath(os.path.join(ROOT, "..", "cinematic-motlab"))
RT = os.path.join(ROOT, "runtime")
IMG = os.path.join(RT, "img")
JS = os.path.join(RT, "js")
os.makedirs(IMG, exist_ok=True)
os.makedirs(JS, exist_ok=True)


def webp(src, name, quality=80):
    im = Image.open(src)
    dst = os.path.join(IMG, name)
    if im.mode in ("RGBA", "LA", "P"):
        im = im.convert("RGBA")
        lossless = im.width * im.height < 20000
        im.save(dst, "WEBP", quality=88, method=6, lossless=lossless)
    else:
        im.convert("RGB").save(dst, "WEBP", quality=quality, method=6)
    return dst


# ---------------------------------------------------------------- scene render patches
# The owner replaced the small E04/F03 portraits with full 16:9 shots (overrides/), so these two scenes
# are drawn full-bleed with a slow push-in instead of a narrow centred card. F03 now shows its own
# "determined" still (the source scene loaded it but drew E04 again).
RENDER_PATCH = {
    "16-E04": r"""
  render(ctx, t, dur, a) {
    // Gaia stands among the people: slow, stable push-in that keeps her face near the upper third
    drawPhotoCamera(ctx, a.portrait, t, dur, { z0: 1.08, z1: 1.17, x0: -10, x1: -42, y0: 22, y1: 84, ease: 'sine' });
    drawAuraRibbons(ctx, t, { intensity: 0.34, yCenter: H * 0.72, count: 2 });
    drawParticles(ctx, t, { count: 40, mode: 'emerald-gold', speed: 0.55, alpha: 0.6, seed: 81 });
    drawFilmGrade(ctx, { vignette: 0.46 });
  }
});""",
    "19-F03": r"""
  render(ctx, t, dur, a) {
    const k = clamp(t / dur);
    // Gaia lifts her gaze to the viewer: forward push-in on her eyes while the aura grows
    drawPhotoCamera(ctx, a.det, t, dur, { z0: 1.04, z1: 1.16, y0: 10, y1: 62, ease: 'sine' });
    const intensity = 0.4 + 0.6 * easeInOutSine(k);
    drawSunShaft(ctx, t, { x: W * 0.5, spread: 640, color: `rgba(246,216,122,${0.1 + 0.14 * k})` });
    drawAuraRibbons(ctx, t, { intensity, yCenter: H * 0.74, count: 3 });
    drawParticles(ctx, t, { count: 60, mode: 'emerald-gold', speed: 1.0, alpha: 0.85, seed: 98 });
    drawFilmGrade(ctx, { vignette: 0.44 });
  }
});""",
}

# ---------------------------------------------------------------- scenes
project =json.load(open(os.path.join(SRC, "project.json"), encoding="utf-8"))
asset_map = {}
blocks = []
timeline = []
for entry in project["scenes"]:
    file = entry if isinstance(entry, str) else entry["file"]
    fade = 0 if isinstance(entry, str) else entry.get("transition", {}).get("duration", 0)
    html = open(os.path.join(SRC, file), encoding="utf-8").read()
    body = re.search(r'<script type="module">([\s\S]*?)</script>', html).group(1)
    body = re.sub(r"import \{[\s\S]*?\} from './cinematic\.js';", "", body)
    body = re.sub(r"^const SUBS = .*$", "const SUBS = null;", body, flags=re.M)

    def repl(m):
        path = m.group(1)
        name = os.path.splitext(os.path.basename(path))[0] + ".webp"
        asset_map[name] = os.path.join(SRC, "scenes", path)
        return f"'img/{name}'"

    body = re.sub(r"'(\.\./assets/[^']+)'", repl, body)
    sid = os.path.splitext(os.path.basename(file))[0]
    if sid in RENDER_PATCH:
        body, n = re.subn(r"render\(ctx, t, dur, a\) \{[\s\S]*$", lambda _m: RENDER_PATCH[sid].strip() + "\n", body)
        assert n == 1, sid
        print(f"render patch: {sid}")
    body = body.replace("mountScene({", f"register({json.dumps(sid)}, GLOBAL_START, {fade}, {{", 1)
    blocks.append("{" + body.rstrip() + "\n}")
    start = float(re.search(r"GLOBAL_START = ([\d.]+)", body).group(1))
    total = float(re.search(r"total: ([\d.]+)", body).group(1))
    timeline.append(dict(id=sid, start=start, total=total, fade=fade))

header = ("// Generated by tools/build_web.py from cinematic-motlab/scenes/*.html - do not edit by hand.\n"
          "import {\n  W, H, TAU, clamp, lerp, span, easeOutCubic, easeOutExpo, easeInOutSine,\n"
          "  drawPhotoCamera, drawFilmGrade, drawSunShaft, drawParticles, drawAuraRibbons,\n"
          "  drawDawnForestA02, drawIlustrasiBadge, drawFactCard, drawSubtitle\n} from './engine.js';\n\n"
          "export const SCENES = [];\n"
          "function register(id, start, fade, def) { SCENES.push({ id, start, fade, ...def }); }\n\n")
open(os.path.join(JS, "scenes.js"), "w", encoding="utf-8").write(header + "\n\n".join(blocks) + "\n")

# ---------------------------------------------------------------- engine
eng = open(os.path.join(SRC, "scenes", "cinematic.js"), encoding="utf-8").read()
eng = eng.replace("// Shared cinematic rendering engine",
                  "// Web runtime build of cinematic-motlab/scenes/cinematic.js (generated by tools/build_web.py).\n"
                  "// Changes: image filters are baked once per image (no per-frame ctx.filter, works on Safari),\n"
                  "// canvas subtitles are disabled (HTML captions), mountScene is replaced by the player.\n"
                  "// Shared cinematic rendering engine")
bake = r'''
// ---- one-time filter baking (replaces per-frame ctx.filter) ----
const _baked = new Map();
function parseFilter(str) {
  const f = { blur: 0, brightness: 1, saturate: 1, contrast: 1 };
  for (const m of str.matchAll(/(blur|brightness|saturate|contrast)\(([\d.]+)(px)?\)/g)) f[m[1]] = parseFloat(m[2]);
  return f;
}
export function bakedImage(img, filter) {
  if (!filter) return img;
  let byImg = _baked.get(img);
  if (!byImg) { byImg = new Map(); _baked.set(img, byImg); }
  if (byImg.has(filter)) return byImg.get(filter);
  const f = parseFilter(filter);
  const iw = img.naturalWidth || img.width, ih = img.naturalHeight || img.height;
  // blur is emulated by drawing small and letting the GPU upscale smoothly (two-step downsample)
  const k = f.blur > 0 ? Math.max(0.035, Math.min(1, 2.2 / f.blur)) : 1;
  let src = img, sw = iw, sh = ih;
  if (k < 0.5) {
    const mid = document.createElement('canvas');
    mid.width = Math.max(2, Math.round(iw * 0.5)); mid.height = Math.max(2, Math.round(ih * 0.5));
    const mc = mid.getContext('2d'); mc.imageSmoothingQuality = 'high'; mc.drawImage(img, 0, 0, mid.width, mid.height);
    src = mid; sw = mid.width; sh = mid.height;
  }
  const cv = document.createElement('canvas');
  cv.width = Math.max(2, Math.round(iw * k)); cv.height = Math.max(2, Math.round(ih * k));
  const c = cv.getContext('2d', { willReadFrequently: true });
  c.imageSmoothingQuality = 'high';
  c.drawImage(src, 0, 0, sw, sh, 0, 0, cv.width, cv.height);
  if (f.brightness !== 1 || f.saturate !== 1 || f.contrast !== 1) {
    const d = c.getImageData(0, 0, cv.width, cv.height), p = d.data;
    for (let i = 0; i < p.length; i += 4) {
      let r = p[i] * f.brightness, g = p[i + 1] * f.brightness, b = p[i + 2] * f.brightness;
      const l = 0.2126 * r + 0.7152 * g + 0.0722 * b;
      r = l + (r - l) * f.saturate; g = l + (g - l) * f.saturate; b = l + (b - l) * f.saturate;
      r = (r - 128) * f.contrast + 128; g = (g - 128) * f.contrast + 128; b = (b - 128) * f.contrast + 128;
      p[i] = r; p[i + 1] = g; p[i + 2] = b;
    }
    c.putImageData(d, 0, 0);
  }
  cv.naturalWidth = iw; cv.naturalHeight = ih;
  byImg.set(filter, cv);
  return cv;
}
'''
eng = eng.replace("// Draw image with cover-fit", bake + "\n// Draw image with cover-fit", 1)
eng = eng.replace("  const imgRatio = img.naturalWidth / img.naturalHeight;",
                  "  const filtered = bakedImage(img, cam.filter);\n"
                  "  const imgRatio = (img.naturalWidth || img.width) / (img.naturalHeight || img.height);", 1)
eng = eng.replace("  if (cam.filter) ctx.filter = cam.filter;\n  ctx.drawImage(img, -dw / 2, -dh / 2, dw, dh);",
                  "  ctx.drawImage(filtered, -dw / 2, -dh / 2, dw, dh);", 1)
eng = eng.replace("export function drawSubtitle(ctx, globalT, subs) {\n  if (!subs || !subs.length) return;",
                  "export function drawSubtitle(ctx, globalT, subs) {\n  if (!subs || !subs.length) return; // web: captions are HTML", 1)
# the owner asked to remove the small "Ilustrasi" corner badge from every shot
eng = eng.replace("export function drawIlustrasiBadge(ctx, t, dur) {\n",
                  "export function drawIlustrasiBadge(ctx, t, dur) {\n  return; // web: badge removed at the owner's request\n", 1)
assert "badge removed" in eng
eng = eng[: eng.index("// Helper to bind the standard motlab page contract")].rstrip() + "\n"
assert "ctx.filter = cam.filter" not in eng and "bakedImage(img, cam.filter)" in eng
open(os.path.join(JS, "engine.js"), "w", encoding="utf-8").write(eng)

# ---------------------------------------------------------------- images
# overrides/<name>.(webp|png|jpg) replaces a source still (e.g. the owner's new G02_yard); never overwritten
OVR = os.path.join(ROOT, "overrides")


def override_for(name):
    stem = os.path.splitext(name)[0]
    for ext in (".webp", ".png", ".jpg", ".jpeg"):
        p = os.path.join(OVR, stem + ext)
        if os.path.exists(p):
            return p
    return None


for name, src in sorted(asset_map.items()):
    ovr = override_for(name)
    if ovr:
        print(f"override: {name} <- overrides/{os.path.basename(ovr)}")
    webp(ovr or src, name, quality=72 if ovr else 80)
# H02 still: the welcoming Gaia, lightly sharpened because the ending shows it large
from PIL import ImageFilter  # noqa: E402
g03 = Image.open(override_for("ending-gaia.webp") or os.path.join(SRC, "assets", "shots", "G03_gaia_welcome.jpg")).convert("RGB")
g03.filter(ImageFilter.UnsharpMask(radius=1.4, percent=55, threshold=2)).save(
    os.path.join(IMG, "ending-gaia.webp"), "WEBP", quality=88, method=6)
bg_ovr = override_for("ending-bg.webp")
if bg_ovr:  # owner's backdrop; shown blurred behind H02, so 640 px is plenty
    print("override: ending-bg.webp <- overrides/" + os.path.basename(bg_ovr))
    bg = Image.open(bg_ovr).convert("RGB")
    bg.resize((640, int(640 * bg.height / bg.width)), Image.LANCZOS).save(os.path.join(IMG, "ending-bg.webp"), "WEBP", quality=72)
else:
    g03.resize((40, int(40 * g03.height / g03.width))).save(os.path.join(IMG, "ending-bg.webp"), "WEBP", quality=70)

# ---------------------------------------------------------------- captions
timings = json.load(open(os.path.join(ROOT, "_build", "timings.json"), encoding="utf-8"))
caps = [dict(start=t["start"], end=round(t["end"] + 0.35, 3), speaker=t["speaker"], id=t["id"], en=t["en"]) for t in timings]
json.dump(caps, open(os.path.join(RT, "captions.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)


def ts(x):
    h, r = divmod(x, 3600)
    m, s = divmod(r, 60)
    return f"{int(h):02d}:{int(m):02d}:{s:06.3f}"


for lang in ("id", "en"):
    lines = ["WEBVTT", ""]
    for i, c in enumerate(caps, 1):
        who = "Gaia" if c["speaker"] == "Gaia" else "Narator"
        lines += [str(i), f"{ts(c['start'])} --> {ts(c['end'])}", f"<v {who}>{c[lang]}", ""]
    open(os.path.join(RT, f"subtitle-{lang}.vtt"), "w", encoding="utf-8").write("\n".join(lines))
tr = ["# TERRA NOVA - Opening Cinematic (transkrip)", ""]
for c in caps:
    tr.append(f"- **{c['speaker']}** ({c['start']:.1f}s): {c['id']}")
open(os.path.join(RT, "transcript-id.md"), "w", encoding="utf-8").write("\n".join(tr) + "\n")

